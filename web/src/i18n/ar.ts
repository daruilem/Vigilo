/** Arabic counting: 1 and 2 have their own forms, 3 to 10 use the plural, 11+ the singular. */
function count(n: number, one: string, two: string, few: (n: number) => string, many: (n: number) => string) {
  if (n === 1) return one;
  if (n === 2) return two;
  if (n >= 3 && n <= 10) return few(n);
  return many(n);
}

